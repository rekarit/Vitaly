/// APP REPOSITORY â€” Single mutable in-memory store for the whole app.
/// MockData provides the seed; everything added via Data Entry lands here.
/// Other modules should read from AppRepository instead of MockData directly
/// once Phase 2+ is wired in.
/// â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
class AppRepository {
  AppRepository._();
  static final AppRepository instance = AppRepository._();

  // â”€â”€ Mutable lists â€” seeded from MockData â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
  final List<MaterialItem> materials = List.of(MockData.materials);
  final List<Slab>         slabs     = List.of(MockData.slabs);

  // â”€â”€ Counters for generating unique IDs â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
  int _materialCounter = MockData.materials.length + 1;
  int _slabCounter     = MockData.slabs.length     + 1;

  String nextMaterialId() => 'mat_${(_materialCounter++).toString().padLeft(3, '0')}';
  String nextSlabId()     => 's_${(_slabCounter++).toString().padLeft(4, '0')}';

  // â”€â”€ Write operations â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
  void addMaterial(MaterialItem m) => materials.add(m);
  void addSlab(Slab s)             => slabs.add(s);

  void addBatch({required MaterialItem material, required List<Slab> batch}) {
    addMaterial(material);
    slabs.addAll(batch);
  }

  // â”€â”€ Read helpers â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
  int get totalSlabs     => slabs.length;
  int get availableSlabs => slabs.where((s) => s.status == SlabStatus.available).length;
}
